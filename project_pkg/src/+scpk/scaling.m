function S = scaling(tol)
%SCALING  許容誤差を1単位とする変数スケーリングを作る.
%
%   S = SCALING(TOL) は各変数の許容誤差 TOL を1単位とする変換を返す.
%   スケール後の変数で書くと, 追従重みはほぼ単位行列になり cond(H) が O(1) に
%   収まる. 重み側で許容誤差を表現する (Q = 1/tol^2) と H に何桁もの開きが
%   生じ, 一次法が収束しない・内点法が閾値を通らないという問題を招く.
%
%   TOL のフィールドは対象問題に合わせて自由に取れる. 例:
%     tol.pos = 5      %% [m]
%     tol.vel = 0.5    %% [m/s]
%     tol.ang = 0.5    %% [deg]
%
%   S のメソッド
%     S.vec     : 変数ごとのスケール係数ベクトルを組む (S.vec([tol.pos tol.vel ...]))
%     S.to(x)   : 物理量 -> スケール後
%     S.from(z) : スケール後 -> 物理量
%
%   使い方の指針: 「1単位ずれたら同じくらい困る」量を tol に取る.
%   そうすればコストは単純な二乗和でよく, 重みチューニングの大半が不要になる.
S.tol = tol;
S.vec = @(v) v(:);
S.to   = @(x,v) x(:)./v(:);
S.from = @(z,v) z(:).*v(:);
end
